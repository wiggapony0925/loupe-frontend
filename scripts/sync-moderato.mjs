/**
 * Re-vendor `moderato` from the standalone ../moderato repo.
 *
 * moderato ships to npm, so its own package.json resolves from `dist`.
 * Metro does not build it — it reads the vendored SOURCE, through the
 * `moderato` alias in metro.config.js and the tsconfig path. Copying that
 * package.json verbatim would therefore point every bare `import … from
 * "moderato"` at a `dist/` that does not exist here, and the failure shows
 * up in a release bundle rather than in the dev server (which is exactly
 * how build 249's archive died, on the sibling ".js suffix" problem).
 *
 * So: copy the source, drop the parts React Native cannot use, and write a
 * package.json that points at `./src`. Version and metadata still come from
 * the canonical repo, so `vendor/moderato` never claims to be a version it
 * isn't.
 *
 * Usage: npm run sync:moderato
 */

import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../moderato");
const target = resolve(here, "../vendor/moderato");

if (!existsSync(source)) {
  console.error(
    `sync:moderato — no checkout at ${source}.\n` +
      `Clone https://github.com/wiggapony0925/moderato next to this repo.`,
  );
  process.exit(1);
}

rmSync(`${target}/src`, { recursive: true, force: true });
cpSync(`${source}/src`, `${target}/src`, { recursive: true });

// `web` is DOM wrappers and `server` is a Node/edge request handler.
// Neither means anything in React Native, and shipping them only gives
// Metro more to resolve.
for (const dropped of ["web", "server"]) {
  rmSync(`${target}/src/${dropped}`, { recursive: true, force: true });
}

const upstream = JSON.parse(readFileSync(`${source}/package.json`, "utf8"));
const vendored = {
  ...upstream,
  // Repointed at source — see the note at the top.
  main: "./src/index.ts",
  types: "./src/index.ts",
  // Dropped rather than repointed: a bundler that honours `module` would
  // otherwise reach for a `dist` that is not vendored.
  module: undefined,
  exports: {
    ".": "./src/index.ts",
    "./react": "./src/react/index.ts",
    "./package.json": "./package.json",
  },
  // Nothing here is packed or published; these would only mislead.
  files: undefined,
  publishConfig: undefined,
  scripts: undefined,
  devDependencies: undefined,
  _vendoredNote:
    "Generated by scripts/sync-moderato.mjs — do not hand-edit. " +
    "Canonical source: https://github.com/wiggapony0925/moderato",
};
writeFileSync(
  `${target}/package.json`,
  `${JSON.stringify(vendored, null, 2)}\n`,
  "utf8",
);

console.log(`sync:moderato — vendored moderato@${upstream.version} (src only)`);
